'use strict';

const content = document.getElementById('content');

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function qrBlock(address) {
  const wrap = document.createElement('div');

  const qr = el('div', 'qr');
  qr.setAttribute('role', 'img');
  qr.setAttribute('aria-label', 'QR code for ' + address.url);
  qr.innerHTML = address.svg; // generated by the bridge itself, not user input
  wrap.appendChild(qr);

  const line = el('p', 'address', address.url);
  line.appendChild(el('small', null, address.adapter));
  wrap.appendChild(line);

  return wrap;
}

function showMessage(text) {
  content.innerHTML = '';
  content.appendChild(el('div', 'empty', text));
}

/** Switch for "Start with Windows". Hidden when this build cannot register itself. */
function startupRow() {
  const row = el('label', 'startup');
  row.hidden = true;

  const text = el('span', null, 'Start with Windows');
  text.appendChild(el('small', null, 'Runs quietly in the tray when you sign in, so your phone keeps working after a restart.'));
  row.appendChild(text);

  const box = document.createElement('input');
  box.type = 'checkbox';
  row.appendChild(box);

  fetch('/api/autostart')
    .then((response) => response.json())
    .then((state) => {
      row.hidden = !state.available;
      box.checked = state.enabled;
    })
    .catch(() => { /* leave it hidden */ });

  box.addEventListener('change', async () => {
    const wanted = box.checked;
    box.disabled = true;
    try {
      const response = await fetch('/api/autostart', {
        method: 'PUT',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ enabled: wanted })
      });
      if (!response.ok) throw new Error('failed');
      box.checked = (await response.json()).enabled;
    } catch {
      box.checked = !wanted;
    } finally {
      box.disabled = false;
    }
  });

  return row;
}

async function load() {
  let data;
  try {
    const response = await fetch('/api/pair');
    if (response.status === 404) {
      showMessage('Open this page on the PC that runs BenQ Bridge, at http://localhost:' + location.port + '/pair.html.');
      return;
    }
    data = await response.json();
  } catch {
    showMessage('Could not reach BenQ Bridge. Check that it is still running.');
    return;
  }

  if (!data.addresses.length) {
    showMessage('This PC is not connected to a network. Connect to Wi-Fi or Ethernet, then reload this page.');
    return;
  }

  content.innerHTML = '';
  const [first, ...others] = data.addresses;
  content.appendChild(qrBlock(first));

  const actions = el('div', 'actions');
  const open = el('a', 'primary', 'Open the controls on this PC');
  open.href = '/#t=' + encodeURIComponent(data.token);
  actions.appendChild(open);
  content.appendChild(actions);

  content.appendChild(startupRow());

  if (others.length) {
    const fold = el('details', 'fold others');
    fold.appendChild(el('summary', null, 'Phone can’t connect? Try another network address'));
    for (const address of others) fold.appendChild(qrBlock(address));
    content.appendChild(fold);
  }

  content.appendChild(el('p', 'help',
    'Nothing loads on the phone? Allow BenQ Bridge through Windows Firewall on private networks, '
    + 'and check the phone is not on a guest Wi-Fi.'));
}

load();
